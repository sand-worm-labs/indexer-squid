// Generates schema.graphql and src/events.ts from abi/Exchange.json.
// Run via `sqd generate`, then `sqd typegen` / `sqd codegen`.
const fs = require('fs')
const path = require('path')

const root = path.join(__dirname, '..')
const abi = JSON.parse(fs.readFileSync(path.join(root, 'abi/Exchange.json'), 'utf8'))

// Overloaded events get a distinct entity name; typegen exports the 2nd+ overload as `<Name>_1`, `_2`, ...
const OVERLOAD_NAMES = {'LinkDsError(uint256,bytes)': 'LinkDsErrorLowLevel'}
// Event params that clash with entity/meta fields are renamed (as in the Envio indexer).
const RENAMES = {id: 'eventId'}
const META = ['block', 'blockTime', 'txHash', 'logIndex']

const gqlType = (t) => {
    const m = t.match(/^(.*?)((\[\d*\])*)$/)
    const base = m[1]
    let scalar
    if (/^u?int\d+$/.test(base)) scalar = 'BigInt'
    else if (base === 'bool') scalar = 'Boolean'
    else if (['address', 'string', 'bytes'].includes(base) || /^bytes\d+$/.test(base)) scalar = 'String'
    else throw new Error(`unsupported type ${t}`)
    const depth = (m[2].match(/\[/g) || []).length
    if (depth > 1) throw new Error(`nested arrays unsupported: ${t}`)
    // Subsquid can't generate columns for BigInt lists, so numeric arrays hold decimal strings.
    return depth ? `[${scalar === 'BigInt' ? 'String' : scalar}!]!` : `${scalar}!`
}

const seen = {}
const events = abi.filter((x) => x.type === 'event').map((e) => {
    const sig = `${e.name}(${e.inputs.map((i) => i.type).join(',')})`
    const n = (seen[e.name] = (seen[e.name] || 0) + 1)
    const abiName = n === 1 ? e.name : `${e.name}_${n - 1}`
    const entityName = n === 1 ? e.name : OVERLOAD_NAMES[sig]
    if (!entityName) throw new Error(`no entity name for overload ${sig}`)
    const fields = e.inputs.map((i) => {
        if (!i.name) throw new Error(`unnamed param in ${sig}`)
        const name = RENAMES[i.name] || i.name
        if (META.includes(name) || name === 'id') throw new Error(`param ${i.name} clashes in ${sig}`)
        return {abiName: i.name, name, type: gqlType(i.type)}
    })
    return {abiName, entity: `Exchange${entityName}`, fields}
})

const schema = events.map((e) => {
    const lines = [
        '  id: ID!',
        '  block: Int! @index',
        '  blockTime: DateTime! @index',
        '  txHash: String!',
        '  logIndex: Int!',
        ...e.fields.map((f) => `  ${f.name}: ${f.type}${/^(perpId|accountId)$/.test(f.name) ? ' @index' : ''}`),
    ]
    return `type ${e.entity} @entity {\n${lines.join('\n')}\n}\n`
}).join('\n')
fs.writeFileSync(path.join(root, 'schema.graphql'), schema)

const table = events.map((e) => {
    const renames = e.fields.filter((f) => f.name !== f.abiName).map((f) => `${f.abiName}: '${f.name}'`)
    return `    bind(abi.${e.abiName}, m.${e.entity}${renames.length ? `, {${renames.join(', ')}}` : ''}),`
}).join('\n')

fs.writeFileSync(path.join(root, 'src/events.ts'), `// Generated by scripts/generate.js from abi/Exchange.json. Do not edit.
import * as abi from './abi/Exchange/events'
import * as m from './model'
import {bind} from './bind'

export const handlers = [
${table}
]
`)
console.log(`generated ${events.length} events`)
